#!/usr/bin/env bash
# Starts the local Supabase-compatible stack (detached, pid files in $KP_E2E_STATE/pids):
#   Postgres (if not running; runs reset-db.sh when there is no cluster yet)
#   smtp-sink, mock-storage, gateway (:GATEWAY_PORT), GoTrue, PostgREST
# Writes $KP_E2E_STATE/keys.env and the app's .env.local (an existing hand-written
# .env.local is moved to .env.local.e2e-backup and restored by stop-stack.sh).
#
#   bash tests/e2e/start-stack.sh            services only
#   bash tests/e2e/start-stack.sh --with-app also `next start` (needs an existing `next build`)
set -euo pipefail
source "$(dirname "$0")/config.sh"

WITH_APP=0
[ "${1:-}" = "--with-app" ] && WITH_APP=1

[ -x "$GOTRUE_DIR/auth" ] && [ -x "$BIN_DIR/postgrest-$POSTGREST_VERSION" ] || die "binaries missing; run tests/e2e/setup.sh first"
mkdir -p "$LOG_DIR" "$PID_DIR" "$MAIL_DIR" "$STORAGE_DIR"

# --- Postgres -------------------------------------------------------------------------
if [ ! -f "$PGDATA_DIR/PG_VERSION" ]; then
  bash "$E2E_DIR/reset-db.sh"
elif ! pg_running; then
  log "starting Postgres"
  "${RUNAS[@]}" "$PGBIN/pg_ctl" -D "$PGDATA_DIR" -w -t 30 -l "$LOG_DIR/postgres.log" \
    -o "-p $PG_PORT -k $PG_SOCKET_DIR -h 127.0.0.1 -c timezone=UTC -c fsync=off -c synchronous_commit=off -c full_page_writes=off -c max_connections=200" \
    start >/dev/null
fi

# --- keys and env files -------------------------------------------------------------------
JWT_SECRET="$JWT_SECRET" node "$E2E_DIR/services/mint-keys.mjs" >"$KEYS_ENV"
# shellcheck disable=SC1090
source "$KEYS_ENV"
cat >>"$KEYS_ENV" <<EOF
JWT_SECRET=$JWT_SECRET
SUPABASE_URL=$SUPABASE_URL
APP_URL=$APP_URL
MAIL_DIR=$MAIL_DIR
DATABASE_URL=$DATABASE_URL
EOF

MARKER="# generated by tests/e2e/start-stack.sh"
ENV_LOCAL="$REPO_ROOT/.env.local"
if [ -f "$ENV_LOCAL" ] && ! head -1 "$ENV_LOCAL" | grep -qF "$MARKER"; then
  [ -f "$ENV_LOCAL.e2e-backup" ] || { mv "$ENV_LOCAL" "$ENV_LOCAL.e2e-backup"; log "moved your .env.local to .env.local.e2e-backup (restored by stop-stack.sh)"; }
fi
cat >"$ENV_LOCAL" <<EOF
$MARKER — local E2E stack, do not commit
NEXT_PUBLIC_SUPABASE_URL=$SUPABASE_URL
NEXT_PUBLIC_SUPABASE_ANON_KEY=$ANON_KEY
SUPABASE_SERVICE_ROLE_KEY=$SERVICE_ROLE_KEY
NEXT_PUBLIC_SITE_URL=$APP_URL
NEXT_PUBLIC_FIRM_NAME="Kreston Pedabo"
SESSION_IDLE_MINUTES=30
STORAGE_PROVIDER=supabase
SUPABASE_STORAGE_BUCKET=$STORAGE_BUCKET
CLIENT_DIRECTORY_MODE=mock
EMAIL_PROVIDER=supabase
DEMO_PASSWORD="$DEMO_PASSWORD"
EOF

check_free() { port_open "$1" && ! pid_alive "$2" && die "port $1 (for $2) is already in use by another process; override with the matching *_PORT variable"; return 0; }

# --- SMTP sink, storage mock, gateway --------------------------------------------------
check_free "$SMTP_PORT" smtp
start_bg smtp env SMTP_PORT="$SMTP_PORT" MAIL_DIR="$MAIL_DIR" node "$E2E_DIR/services/smtp-sink.mjs"
check_free "$STORAGE_PORT" storage
start_bg storage env STORAGE_PORT="$STORAGE_PORT" STORAGE_DIR="$STORAGE_DIR" JWT_SECRET="$JWT_SECRET" node "$E2E_DIR/services/mock-storage.mjs"
check_free "$GATEWAY_PORT" gateway
start_bg gateway env GATEWAY_PORT="$GATEWAY_PORT" GOTRUE_PORT="$GOTRUE_PORT" POSTGREST_PORT="$POSTGREST_PORT" \
  STORAGE_PORT="$STORAGE_PORT" TEMPLATES_DIR="$REPO_ROOT/supabase/templates" node "$E2E_DIR/services/gateway.mjs"
wait_port "$SMTP_PORT" smtp
wait_http "http://127.0.0.1:$STORAGE_PORT/health" storage
wait_http "http://127.0.0.1:$GATEWAY_PORT/__health" gateway

# --- GoTrue ------------------------------------------------------------------------------
T="http://127.0.0.1:$GATEWAY_PORT/__templates"
check_free "$GOTRUE_PORT" gotrue
(
  cd "$GOTRUE_DIR"
  start_bg gotrue env \
    GOTRUE_API_HOST=127.0.0.1 PORT="$GOTRUE_PORT" API_EXTERNAL_URL="$SUPABASE_URL/auth/v1" \
    GOTRUE_DB_DRIVER=postgres DATABASE_URL="$GOTRUE_DATABASE_URL" GOTRUE_DB_NAMESPACE=auth \
    GOTRUE_DB_MIGRATIONS_PATH="$GOTRUE_DIR/migrations" \
    GOTRUE_SITE_URL="$APP_URL" GOTRUE_URI_ALLOW_LIST="$APP_URL/**" \
    GOTRUE_JWT_SECRET="$JWT_SECRET" GOTRUE_JWT_EXP=3600 GOTRUE_JWT_AUD=authenticated \
    GOTRUE_JWT_DEFAULT_GROUP_NAME=authenticated GOTRUE_JWT_ADMIN_ROLES=service_role \
    GOTRUE_DISABLE_SIGNUP=true GOTRUE_EXTERNAL_EMAIL_ENABLED=true GOTRUE_EXTERNAL_PHONE_ENABLED=false \
    GOTRUE_MAILER_AUTOCONFIRM=false GOTRUE_MAILER_SECURE_EMAIL_CHANGE_ENABLED=true GOTRUE_MAILER_OTP_EXP=3600 \
    GOTRUE_PASSWORD_MIN_LENGTH=10 \
    GOTRUE_PASSWORD_REQUIRED_CHARACTERS="abcdefghijklmnopqrstuvwxyz:ABCDEFGHIJKLMNOPQRSTUVWXYZ:0123456789" \
    GOTRUE_SECURITY_REFRESH_TOKEN_ROTATION_ENABLED=true GOTRUE_SESSIONS_TIMEBOX=12h \
    GOTRUE_MFA_TOTP_ENROLL_ENABLED=true GOTRUE_MFA_TOTP_VERIFY_ENABLED=true GOTRUE_MFA_MAX_ENROLLED_FACTORS=5 \
    GOTRUE_SMTP_HOST=127.0.0.1 GOTRUE_SMTP_PORT="$SMTP_PORT" GOTRUE_SMTP_ADMIN_EMAIL="pbc-portal@kp.test" \
    GOTRUE_SMTP_SENDER_NAME="Kreston Pedabo PBC Portal" GOTRUE_SMTP_MAX_FREQUENCY=1s \
    GOTRUE_MAILER_URLPATHS_INVITE=/auth/v1/verify GOTRUE_MAILER_URLPATHS_CONFIRMATION=/auth/v1/verify \
    GOTRUE_MAILER_URLPATHS_RECOVERY=/auth/v1/verify GOTRUE_MAILER_URLPATHS_EMAIL_CHANGE=/auth/v1/verify \
    GOTRUE_MAILER_TEMPLATES_INVITE="$T/invite.html" GOTRUE_MAILER_TEMPLATES_MAGIC_LINK="$T/magic_link.html" \
    GOTRUE_MAILER_TEMPLATES_RECOVERY="$T/recovery.html" \
    GOTRUE_MAILER_SUBJECTS_INVITE="You've been invited to the Kreston Pedabo PBC Portal" \
    GOTRUE_MAILER_SUBJECTS_MAGIC_LINK="Your PBC Portal sign-in link" \
    GOTRUE_MAILER_SUBJECTS_RECOVERY="Reset your PBC Portal password" \
    GOTRUE_RATE_LIMIT_EMAIL_SENT=100000 GOTRUE_RATE_LIMIT_VERIFY=100000 GOTRUE_RATE_LIMIT_TOKEN_REFRESH=100000 \
    GOTRUE_RATE_LIMIT_OTP=100000 GOTRUE_RATE_LIMIT_SSO=100000 GOTRUE_RATE_LIMIT_ANONYMOUS_USERS=100000 \
    GOTRUE_LOG_LEVEL="${GOTRUE_LOG_LEVEL:-info}" \
    ./auth serve
)

# --- PostgREST ---------------------------------------------------------------------------
cat >"$KP_E2E_STATE/postgrest.conf" <<EOF
db-uri = "postgres://postgres@127.0.0.1:$PG_PORT/postgres"
db-schemas = "public"
db-anon-role = "anon"
db-extra-search-path = "public, extensions"
db-max-rows = 2000
db-pool = 20
jwt-secret = "$JWT_SECRET"
server-host = "127.0.0.1"
server-port = $POSTGREST_PORT
log-level = "warn"
EOF
check_free "$POSTGREST_PORT" postgrest
start_bg postgrest "$BIN_DIR/postgrest-$POSTGREST_VERSION" "$KP_E2E_STATE/postgrest.conf"

wait_http "http://127.0.0.1:$GOTRUE_PORT/health" gotrue 30
wait_http "http://127.0.0.1:$POSTGREST_PORT/" postgrest 30
# Through the gateway, as the app sees it
curl -sf --noproxy '*' -o /dev/null -H "apikey: $SERVICE_ROLE_KEY" -H "Authorization: Bearer $SERVICE_ROLE_KEY" "$SUPABASE_URL/rest/v1/engagement_types?select=id&limit=1" \
  || die "PostgREST not reachable through the gateway"
log "stack up: gateway $SUPABASE_URL  (GoTrue :$GOTRUE_PORT, PostgREST :$POSTGREST_PORT, storage :$STORAGE_PORT, smtp :$SMTP_PORT, pg :$PG_PORT)"

if [ "$WITH_APP" = 1 ]; then
  [ -f "$REPO_ROOT/.next/BUILD_ID" ] || die "no Next build; run: (cd $REPO_ROOT && npx next build)"
  check_free "$APP_PORT" next
  (cd "$REPO_ROOT" && start_bg next npx next start -p "$APP_PORT")
  wait_http "$APP_URL/login" next 60
  log "app up: $APP_URL"
fi
